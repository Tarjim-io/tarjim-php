// Generates src/Lookup/LikelyScripts.php from this Node's ICU/CLDR data:
//   node scripts/likely-scripts.mjs > src/Lookup/LikelyScripts.php
// PHP has no likely-subtags API, and the locale matcher must agree with the JS core, which asks
// Intl.Locale(tag).maximize().script. The output is committed so the package needs neither Node
// nor ext-intl at runtime; rerun this only to move to a newer CLDR.

const letters = 'abcdefghijklmnopqrstuvwxyz';

function* codes(length, prefix = '') {
  if (length === 0) {
    yield prefix;
    return;
  }
  for (const c of letters) yield* codes(length - 1, prefix + c);
}

const locale = (tag) => {
  try {
    return new Intl.Locale(tag);
  } catch {
    return null;
  }
};

const regions = [...codes(2)].concat(Array.from({ length: 1000 }, (_, n) => String(n).padStart(3, '0')));

const regionAliases = {};
for (const region of regions) {
  const canonical = locale(`und-${region}`)?.region?.toLowerCase();
  if (canonical !== undefined && canonical !== region) regionAliases[region] = canonical;
}
// The matcher canonicalises a region before looking it up, so an alias never needs an entry of its own.
const canonicalRegions = regions.filter((region) => !(region in regionAliases));

const everyLanguage = [...codes(2), ...codes(3)];

// A canonical form can carry a script or region of its own (sh is sr-Latn), so it is kept whole.
const languageAliases = {};
for (const language of everyLanguage) {
  const canonical = locale(language)?.baseName.toLowerCase();
  if (canonical !== undefined && canonical !== language) languageAliases[language] = canonical;
}

// A few region aliases depend on the language (az-SU is az-AZ, ru-SU is ru-RU), and the old sign-language
// tags (sgn-GB) are languages of their own; the exceptions to the two tables above are kept per language.
const pairAliases = {};
const expected = (language, region) => {
  const parts = (languageAliases[language] ?? language).split('-');
  const own = parts.find((part, i) => i > 0 && part.length !== 4);
  const script = parts.find((part, i) => i > 0 && part.length === 4);
  return [parts[0], script, own ?? regionAliases[region] ?? region].filter(Boolean).join('-');
};
const probe = (language, region) => {
  const actual = locale(`${language}-${region}`)?.baseName.toLowerCase();
  if (actual !== undefined && actual !== expected(language, region)) ((pairAliases[language] ??= {})[actual] ??= []).push(region);
};
// An alias language reaches its canonical form first, so only the canonical ones need their own entries.
for (const language of everyLanguage) if (!(language in languageAliases)) for (const region in regionAliases) probe(language, region);
for (const region of regions) probe('sgn', region);

const defaultScripts = {};
const overrides = {};
for (const language of everyLanguage) {
  if (language in languageAliases) continue;
  const script = locale(language)?.maximize().script?.toLowerCase();
  if (script === undefined) continue;
  defaultScripts[language] = script;
  for (const region of canonicalRegions) {
    const regional = locale(`${language}-${region}`)?.maximize().script?.toLowerCase();
    if (regional !== undefined && regional !== script) {
      ((overrides[language] ??= {})[regional] ??= []).push(region);
    }
  }
}

const scriptAliases = {};
for (const script of codes(4)) {
  const canonical = locale(`und-${script}`)?.script?.toLowerCase();
  if (canonical !== undefined && canonical !== script) scriptAliases[script] = canonical;
}

const q = (s) => `'${s}'`;
const map = (entries, indent = '        ') =>
  entries.map(([key, value]) => `${indent}${q(key)} => ${value},`).join('\n');
const byScript = {};
for (const [language, script] of Object.entries(defaultScripts)) (byScript[script] ??= []).push(language);

const out = [];
out.push(`<?php

declare(strict_types=1);

namespace Tarjim\\Lookup;

/**
 * Likely scripts and canonical spellings of language, script and region subtags, as ICU ${process.versions.icu}
 * (CLDR ${process.versions.cldr}) reports them through Intl.Locale. Generated by scripts/likely-scripts.mjs:
 * rerun that script, never edit this file by hand.
 */
final class LikelyScripts
{
    /** Language subtags ICU rewrites, to the canonical tag they stand for (language, script and region as one). */
    public const LANGUAGE_ALIASES = [
${map(Object.entries(languageAliases).sort(), '        ').replace(/=> ([^,\n]+),/g, (_, v) => `=> ${q(v)},`)}
    ];

    /** Deprecated regions, to the region that replaces them. */
    public const REGION_ALIASES = [
${map(Object.entries(regionAliases).sort().map(([k, v]) => [k, q(v)]))}
    ];

    /** Deprecated scripts, to the script that replaces them. */
    public const SCRIPT_ALIASES = [
${map(Object.entries(scriptAliases).sort().map(([k, v]) => [k, q(v)]))}
    ];

    /** Language => canonical tag (language and region as one) => the regions it replaces, where that is not what the two tables above give. */
    public const PAIR_ALIASES = [
${Object.keys(pairAliases).sort().map((language) => `        ${q(language)} => [${Object.entries(pairAliases[language]).sort().map(([target, rs]) => `${q(target)} => ${q(rs.join(' '))}`).join(', ')}],`).join('\n')}
    ];

    /** Script => the languages written in it unless the region says otherwise (space separated). */
    public const DEFAULT_SCRIPTS = [
${map(Object.entries(byScript).sort().map(([script, langs]) => [script, q(langs.sort().join(' '))]))}
    ];

    /** Language => script => the regions where that script, not the default, is likely (space separated). */
    public const REGION_SCRIPTS = [`);
for (const language of Object.keys(overrides).sort()) {
  const parts = Object.entries(overrides[language])
    .sort()
    .map(([script, rs]) => `${q(script)} => ${q(rs.join(' '))}`);
  out.push(`        ${q(language)} => [${parts.join(', ')}],`);
}
out.push(`    ];
}
`);
process.stdout.write(out.join('\n'));
